-- 1. TAIKHOAN
CREATE TABLE TAIKHOAN
(
    maTaiKhoan INT IDENTITY(1,1) NOT NULL,
    tenDangNhap VARCHAR(50) NOT NULL,
    matKhau VARCHAR(255) NOT NULL,
    vaiTro NVARCHAR(50) NOT NULL,

