    maTaiKhoan INT NOT NULL,

    CONSTRAINT PK_GIAOVIEN
        PRIMARY KEY (maGiaoVien),

    CONSTRAINT UQ_GIAOVIEN_SODIENTHOAI
        UNIQUE (soDienThoai),

    CONSTRAINT UQ_GIAOVIEN_MATAIKHOAN
        UNIQUE (maTaiKhoan)
);
GO
